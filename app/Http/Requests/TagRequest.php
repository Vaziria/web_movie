<?php

namespace App\Http\Requests;

use App\Models\Tag;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class TagRequest extends FormRequest
{
    public function authorize(): bool
    {
        return (bool) $this->user()?->is_admin;
    }

    protected function prepareForValidation(): void
    {
        // Derive the slug from the name when creating without an explicit slug.
        if ($this->creating() && blank($this->input('slug')) && is_string($this->input('name'))) {
            $this->merge(['slug' => Tag::slugFor($this->input('name'))]);
        }
    }

    /** True when creating (name required). UpdateTagRequest makes everything optional. */
    protected function creating(): bool
    {
        return ! $this->route('tag');
    }

    public function rules(): array
    {
        $tag = $this->route('tag');

        // The comments below are the field descriptions in docs/openapi.json (generated by Scramble).
        return [
            /**
             * Tag name as shown on the site (`#Korea`).
             *
             * @example Korea
             */
            'name' => [$this->creating() ? 'required' : 'sometimes', 'string', 'max:50'],
            /**
             * URL of the tag page (`/tag/{slug}`): lowercase letters, digits and single dashes, unique. Generated
             * from `name` when left out. Changing it changes the page URL.
             *
             * @example korea
             */
            'slug' => ['sometimes', 'filled', 'string', 'max:60', 'regex:/^[a-z0-9]+(?:-[a-z0-9]+)*$/', Rule::unique('tags', 'slug')->ignore($tag?->id)],
        ];
    }

    public function messages(): array
    {
        return ['slug.regex' => 'The slug may only contain lowercase letters, numbers and single dashes.'];
    }
}
