<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;

class CategoryRequest extends FormRequest
{
    public function authorize(): bool
    {
        return (bool) $this->user()?->is_admin;
    }

    protected function prepareForValidation(): void
    {
        // Derive the slug from the name when creating without an explicit slug.
        if (! $this->route('category') && blank($this->input('slug')) && is_string($this->input('name'))) {
            $this->merge(['slug' => Str::slug($this->input('name'))]);
        }
    }

    /** True when creating (name required). UpdateCategoryRequest makes everything optional. */
    protected function creating(): bool
    {
        return ! $this->route('category');
    }

    public function rules(): array
    {
        $category = $this->route('category');

        // The comments below are the field descriptions in docs/openapi.json (generated by Scramble).
        return [
            /**
             * Category name, shown on chips and the category page.
             *
             * @example Sci-Fi
             */
            'name' => [$this->creating() ? 'required' : 'sometimes', 'string', 'max:100'],
            /**
             * URL of the category page (`/category/{slug}`): lowercase letters, digits and single dashes, unique.
             * Generated from `name` when left out. Changing it changes the page URL.
             *
             * @example sci-fi
             */
            'slug' => ['sometimes', 'filled', 'string', 'max:120', 'regex:/^[a-z0-9]+(?:-[a-z0-9]+)*$/', Rule::unique('categories', 'slug')->ignore($category?->id)],
            /**
             * Shown on the category page and used as its Google description: write 1-2 useful sentences.
             *
             * @example Space, time and robots.
             */
            'description' => ['sometimes', 'nullable', 'string', 'max:2000'],
        ];
    }

    public function messages(): array
    {
        return ['slug.regex' => 'The slug may only contain lowercase letters, numbers and single dashes.'];
    }
}
