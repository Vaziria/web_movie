<?php

namespace App\Http\Requests;

use App\Models\Movie;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;
use Illuminate\Validation\Validator;
use Throwable;

class MovieRequest extends FormRequest
{
    public function authorize(): bool
    {
        return (bool) $this->user()?->is_admin;
    }

    protected function prepareForValidation(): void
    {
        // Accept a pasted `<iframe src="...">` embed code as embed_url by pulling out its src.
        $embed = $this->input('embed_url');
        if (is_string($embed)) {
            $this->merge(['embed_url' => Movie::extractEmbedSrc($embed)]);
        }

        // Backup players: JSON array, or one per line (admin textarea / multipart). Each may be iframe code.
        $backups = $this->input('backup_embed_urls');
        if (is_string($backups)) {
            $backups = preg_split('/\R/', $backups);
        }
        if (is_array($backups)) {
            $this->merge(['backup_embed_urls' => array_values(array_filter(
                array_map(fn ($b) => is_string($b) ? Movie::extractEmbedSrc($b) : $b, $backups),
                fn ($b) => $b !== '' && $b !== null,
            ))]);
        }

        // Multipart forms send categories as "Action, Drama"; JSON sends an array.
        $categories = $this->input('categories');
        if (is_string($categories)) {
            $this->merge(['categories' => array_values(array_filter(array_map('trim', explode(',', $categories))))]);
        }

        // A thumbnail file wins over a URL. In the admin form an empty URL box means "keep the current thumbnail"
        // (removal is an explicit checkbox), so drop it instead of letting it clear the field.
        if ($this->hasFile('thumbnail') || ($this->boolean('_admin_form') && blank($this->input('thumbnail_url')))) {
            $this->request->remove('thumbnail_url');
        }

        // Admin form: the date box only counts when "Schedule" is picked.
        if ($this->boolean('_admin_form') && $this->input('status') !== 'scheduled') {
            $this->request->remove('published_at');
        }
    }

    /** True when creating a movie (title and embed_url required). UpdateMovieRequest makes everything optional. */
    protected function creating(): bool
    {
        return ! $this->route('movie');
    }

    public function rules(): array
    {
        $movie = $this->route('movie');
        $required = $this->creating() ? 'required' : 'sometimes';

        // The comments below are the field descriptions in docs/openapi.json (generated by Scramble).
        return [
            /**
             * Movie title.
             *
             * @example Night Train
             */
            'title' => [$required, 'string', 'max:255'],
            /**
             * URL path of the movie page (`/movies/{slug}`). Generated from the title when left out
             * (`night-train`, then `night-train-2`, ...). Changing it changes the page URL.
             *
             * @example night-train
             */
            'slug' => ['sometimes', 'nullable', 'alpha_dash', 'max:255', Rule::unique('movies', 'slug')->ignore($movie?->id)],
            /**
             * Player (Server 1). An `https` player URL **or the whole `<iframe src="...">` embed code** from the
             * video host (its `src` is used). `https://vidara.to/v/<id>` is rewritten to `https://vidara.to/e/<id>`.
             *
             * @var string
             *
             * @example <iframe src="https://vidara.to/e/8SdwOuKAAk92t" width="640" height="360" frameborder="0" allowfullscreen></iframe>
             */
            'embed_url' => [$required, 'string', 'max:2048', 'url:https'],
            /**
             * Up to 5 backup players, shown as Server 2, 3, ... Each item is an `https` URL or iframe code.
             * JSON: an array. Multipart: one per line. Duplicates and copies of `embed_url` are dropped;
             * `[]` or `null` removes them all.
             *
             * @var string[]|null
             *
             * @example ["https://vidara.to/e/AnotherId"]
             */
            'backup_embed_urls' => ['sometimes', 'nullable', 'array', 'max:'.Movie::MAX_BACKUPS],
            'backup_embed_urls.*' => ['string', 'max:2048', 'url:https'],
            /**
             * Thumbnail as a remote image URL (16:9 looks best). Ignored when a `thumbnail` file is sent.
             * `null` removes the current thumbnail.
             *
             * @example https://example.com/night-train.jpg
             */
            'thumbnail_url' => ['sometimes', 'nullable', 'string', 'max:2048', 'url:http,https'],
            /**
             * Thumbnail image file (multipart only): jpg, png or webp, max 2 MB, 16:9 (e.g. 1280x720).
             * Replaces (and deletes) the previous uploaded file.
             */
            'thumbnail' => ['sometimes', 'file', 'image', 'mimes:jpg,jpeg,png,webp', 'max:2048'],
            /**
             * Description. The first ~155 characters become the page's Google description.
             *
             * @example A long ride through the night.
             */
            'synopsis' => ['sometimes', 'nullable', 'string', 'max:10000'],
            /**
             * Release year.
             *
             * @example 2024
             */
            'release_year' => ['sometimes', 'nullable', 'integer', 'between:1870,2100'],
            /**
             * Length in minutes. Shown as `1j 45m` / `1h 45m` and used by `sort=duration`.
             *
             * @example 104
             */
            'duration_minutes' => ['sometimes', 'nullable', 'integer', 'between:1,1440'],
            /**
             * Category names (max 10). JSON: an array. Multipart: comma separated (`Drama, Thriller`).
             * Matched by slug (`sci fi` = `Sci-Fi`); unknown names create a category. On update the list
             * replaces the old one (`[]` clears it); leave it out to keep the categories.
             *
             * @var string[]|null
             *
             * @example ["Drama", "Thriller"]
             */
            'categories' => ['sometimes', 'nullable', 'array', 'max:10'],
            'categories.*' => ['string', 'max:100'],
            /** Update only: `true` removes the current thumbnail. */
            'remove_thumbnail' => ['sometimes', 'boolean'],
            /**
             * `published` (live; the default for new movies), `draft` (hidden from visitors) or `scheduled`
             * (goes live by itself at `published_at`). On update, leaving it out keeps the current status;
             * `published` on a movie that is already live keeps its original date.
             *
             * @example scheduled
             */
            'status' => ['sometimes', 'in:draft,published,scheduled'],
            /**
             * Publish time. Required for `scheduled` (must be in the future); for `published` it must not be in
             * the future. **Without an offset it is read as WIB** (`Asia/Jakarta`): `2026-11-08 20:00` =
             * 13:00 UTC. With an offset (`+07:00`, `Z`) it is used as given. Sending `null` without `status`
             * makes the movie a draft.
             *
             * @var string|null
             *
             * @example 2026-11-08 20:00
             */
            'published_at' => ['nullable', 'date', 'required_if:status,scheduled'],
        ];
    }

    /** A scheduled time must be in the future; "published" cannot be in the future. */
    public function after(): array
    {
        return [function (Validator $validator) {
            if ($validator->errors()->has('published_at') || blank($this->input('published_at'))) {
                return;
            }
            try {
                $at = Movie::parsePublishedAt($this->input('published_at'));
            } catch (Throwable) {
                $validator->errors()->add('published_at', 'The published at field must be a valid date.');

                return;
            }
            $status = $this->input('status');
            if ($status === 'scheduled' && ! $at->isFuture()) {
                $validator->errors()->add('published_at', 'The scheduled time must be in the future.');
            } elseif ($status === 'published' && $at->isFuture()) {
                $validator->errors()->add('published_at', 'A future time needs status "scheduled".');
            }
        }];
    }
}
